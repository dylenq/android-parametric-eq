#!/usr/bin/env python3
"""Generate the EQ adaptive launcher icon (vector drawables) and docs/icon.svg.

Geometry and colours come from the macOS icon (scripts/make-icon.swift in the macOS repo):
tile 100..924 px, vertical gradient 2c2e35 -> 15161a, f2f3f5 curve (boost peak, cut dip),
blue 4da3ff node ringed 1f2025. Standard library only. Run: python3 -I scripts/make-android-icon.py
"""
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "app" / "src" / "main" / "res"
DOCS = ROOT / "docs"

S = 72.0 / 824.0  # px -> dp
SAFE_RADIUS = 33.0
PEAK_X = 220 + 584 * 0.34  # 418.56
DIP_X = 220 + 584 * 0.74  # 652.2


def y_img(x):
    return 577 - 210 * math.exp(-(((x - PEAK_X) / 95) ** 2)) + 120 * math.exp(-(((x - DIP_X) / 85) ** 2))


def xs():
    out = list(range(220, 804, 4))
    out.append(804)
    return out


def to_dp(px):
    return (px - 512) * S + 54


NODE_PX = (PEAK_X, y_img(PEAK_X))
NODE_DP = (to_dp(NODE_PX[0]), to_dp(NODE_PX[1]))

HEADER = "<!-- Generated by scripts/make-android-icon.py. Do not edit by hand. -->\n"


def curve_dp():
    pts = [(to_dp(x), to_dp(y_img(x))) for x in xs()]
    for (px, py) in pts:
        d = math.hypot(px - 54, py - 54)
        if d > SAFE_RADIUS:
            sys.exit("point (%.2f, %.2f) is %.2f dp from centre, outside the %.0f dp safe circle" % (px, py, d, SAFE_RADIUS))
    return pts


def path_data(pts):
    parts = []
    for i, (px, py) in enumerate(pts):
        parts.append("%s%.2f,%.2f" % ("M" if i == 0 else "L", px, py))
    return "".join(parts)


def circle_path(cx, cy, r):
    return "M%.2f,%.2f m-%.2f,0 a%.2f,%.2f 0 1,1 %.2f,0 a%.2f,%.2f 0 1,1 -%.2f,0" % (
        cx, cy, r, r, r, 2 * r, r, r, 2 * r)


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def main():
    pts = curve_dp()
    d = path_data(pts)
    cx, cy = NODE_DP

    background = (
        '<?xml version="1.0" encoding="utf-8"?>\n' + HEADER +
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    xmlns:aapt="http://schemas.android.com/aapt"\n'
        '    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
        '    <path android:pathData="M0,0h108v108h-108z">\n'
        '        <aapt:attr name="android:fillColor">\n'
        '            <gradient\n                android:type="linear"\n'
        '                android:startX="0"\n                android:startY="0"\n'
        '                android:endX="0"\n                android:endY="108"\n'
        '                android:startColor="#2c2e35"\n                android:endColor="#15161a" />\n'
        '        </aapt:attr>\n    </path>\n</vector>\n')
    write(RES / "drawable" / "ic_launcher_background.xml", background)

    foreground = (
        '<?xml version="1.0" encoding="utf-8"?>\n' + HEADER +
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
        '    <path\n        android:pathData="%s"\n        android:strokeColor="#f2f3f5"\n'
        '        android:strokeWidth="3.5"\n        android:strokeLineCap="round"\n'
        '        android:strokeLineJoin="round" />\n'
        '    <path\n        android:pathData="%s"\n        android:fillColor="#1f2025" />\n'
        '    <path\n        android:pathData="%s"\n        android:fillColor="#4da3ff" />\n'
        '</vector>\n') % (d, circle_path(cx, cy, 62 * S), circle_path(cx, cy, 44 * S))
    write(RES / "drawable" / "ic_launcher_foreground.xml", foreground)

    mono = (
        '<?xml version="1.0" encoding="utf-8"?>\n' + HEADER +
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
        '    <path\n        android:pathData="%s"\n        android:strokeColor="#000000"\n'
        '        android:strokeWidth="3.5"\n        android:strokeLineCap="round"\n'
        '        android:strokeLineJoin="round" />\n'
        '    <path\n        android:pathData="%s"\n        android:fillColor="#000000" />\n'
        '</vector>\n') % (d, circle_path(cx, cy, 4.6))
    write(RES / "drawable" / "ic_launcher_monochrome.xml", mono)

    adaptive = (
        '<?xml version="1.0" encoding="utf-8"?>\n' + HEADER +
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@drawable/ic_launcher_background" />\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
        '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
        '</adaptive-icon>\n')
    write(RES / "mipmap-anydpi" / "ic_launcher.xml", adaptive)

    poly = " ".join("%.2f,%.2f" % (x, y_img(x)) for x in xs())
    svg = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<!-- Generated by scripts/make-android-icon.py. Do not edit by hand. -->\n'
        '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">\n'
        '  <defs>\n    <linearGradient id="g" x1="0" y1="0" x2="0" y2="1">\n'
        '      <stop offset="0" stop-color="#2c2e35"/>\n      <stop offset="1" stop-color="#15161a"/>\n'
        '    </linearGradient>\n  </defs>\n'
        '  <rect x="100" y="100" width="824" height="824" rx="186" ry="186" fill="url(#g)"/>\n'
        '  <polyline points="%s" fill="none" stroke="#f2f3f5" stroke-width="40" stroke-linecap="round" stroke-linejoin="round"/>\n'
        '  <circle cx="%.2f" cy="%.2f" r="62" fill="#1f2025"/>\n'
        '  <circle cx="%.2f" cy="%.2f" r="44" fill="#4da3ff"/>\n'
        '</svg>\n') % (poly, NODE_PX[0], NODE_PX[1], NODE_PX[0], NODE_PX[1])
    write(DOCS / "icon.svg", svg)


if __name__ == "__main__":
    main()
